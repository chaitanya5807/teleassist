"""Streamlit chat UI for the TeleAssist API."""

import os

import requests
import streamlit as st

API = os.environ.get("TELEASSIST_API", "http://127.0.0.1:8000")

st.set_page_config(page_title="TeleAssist", page_icon="📡", layout="wide")
st.title("TeleAssist")
st.caption(
    "Answers about Indian telecom consumer rules, grounded in TRAI/DoT regulations and "
    "operator charters. Retrieval-only mode is instant; generated answers run a small "
    "language model and can be slow without a GPU."
)

with st.sidebar:
    st.header("Settings")
    mode = st.selectbox("Retrieval mode", ["hybrid_rerank", "dense", "hybrid", "bm25"])
    generate = st.toggle("Generate an answer (slow on CPU)", value=False)
    use_lora = st.toggle("Use LoRA adapter", value=True, disabled=not generate)
    st.markdown("---")
    try:
        health = requests.get(f"{API}/health", timeout=5).json()
        st.success(f"API online | {health['chunks']} chunks")
        if generate and use_lora and not health["adapter_available"]:
            st.warning("LoRA adapter not found on the server. Turn off the LoRA toggle.")
    except requests.RequestException:
        st.error(f"API not reachable at {API}")
    st.caption("Citations and retrieved passages are always shown so answers can be checked.")

question = st.text_input("Ask a question", placeholder="How many days does number porting take?")
if st.button("Ask", type="primary") and question.strip():
    payload = {"question": question, "mode": mode, "generate": generate, "use_lora": use_lora}
    with st.spinner("Working..."):
        try:
            resp = requests.post(f"{API}/ask", json=payload, timeout=900)
        except requests.RequestException as exc:
            st.error(f"Request failed: {exc}")
            st.stop()
    if resp.status_code != 200:
        st.error(f"API error {resp.status_code}: {resp.json().get('detail', resp.text)}")
        st.stop()
    data = resp.json()

    if data["generated"]:
        st.subheader("Answer")
        if data["abstained"]:
            st.info(data["answer"])
        else:
            st.write(data["answer"])
        if data["invalid_citation_numbers"]:
            st.warning(f"The answer cites passages that do not exist: {data['invalid_citation_numbers']}")
        st.caption(
            "Generated by a 1.5B model. It can state things that its cited passage does not "
            "support, so check the passages below."
        )
        if data["citations"]:
            with st.expander("Cited sources", expanded=True):
                for c in data["citations"]:
                    st.markdown(f"**{c['doc_title']}** ({c['year'] or 'n/a'}) | family {c['family']}")
                    st.caption(c["snippet"])
    else:
        st.subheader("Top passages")

    with st.expander("Retrieved passages", expanded=not data["generated"]):
        for r in data["retrieved"]:
            st.markdown(f"**[{r['rank']}] {r['doc_title']}** ({r['year'] or 'n/a'}) | {r['family']}")
            st.write(r["snippet"])
    lat = data["latency_ms"]
    st.caption(
        f"mode: {data['mode']} | retrieval {lat['retrieval']:.0f} ms | "
        f"generation {lat['generation']:.0f} ms | total {lat['total']:.0f} ms"
    )
